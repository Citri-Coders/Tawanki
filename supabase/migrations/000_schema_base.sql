  ('Textiles & Hamacas',   'Hamacas artesanales de Masaya, telares y bordados típicos',                'chair'),
  ('Frutas & Hortalizas',  'Frutas de temporada, cítricos y vegetales de huertos locales',              'nutrition')
on conflict (nombre) do update
  set descripcion = excluded.descripcion,
      icono       = excluded.icono;

-- ----------------------------------------------------------------------------
-- Productores
-- ----------------------------------------------------------------------------
create table if not exists public.productores (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  nombre_cooperativa_o_taller text not null,
  descripcion text not null default '',
  municipio text not null default '',
  telefono_whatsapp text not null default '',
  departamento_id bigint not null references public.departamentos(id),
  rubro_id bigint not null references public.rubros(id),
  verificado_intur boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists productores_departamento_idx on public.productores(departamento_id);
create index if not exists productores_rubro_idx on public.productores(rubro_id);

-- ----------------------------------------------------------------------------
-- Empresas turísticas
-- ----------------------------------------------------------------------------
create table if not exists public.empresas_turisticas (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  nombre_comercial text not null,
  tipo text not null default 'Hotel',
  departamento_id bigint not null references public.departamentos(id),
  municipio text not null default '',
  registro_turistico_intur text,
  telefono_corporativo text not null default '',
  requerimientos_principales text not null default '',
  verificado_intur boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists empresas_departamento_idx on public.empresas_turisticas(departamento_id);

-- ----------------------------------------------------------------------------
-- Productos
-- ----------------------------------------------------------------------------
create table if not exists public.productos (
  id uuid primary key default gen_random_uuid(),
  productor_id uuid not null references public.productores(id) on delete cascade,
  rubro_id bigint not null references public.rubros(id),
  nombre text not null,
  descripcion text not null default '',
  precio_unitario numeric(12,2) not null default 0 check (precio_unitario >= 0),
  unidad_medida text not null default 'unidad',
  badge_distintivo text not null default 'Disponible',
  imagen_url text,
  disponible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists productos_productor_idx on public.productos(productor_id);
create index if not exists productos_rubro_idx on public.productos(rubro_id);
create index if not exists productos_created_idx on public.productos(created_at desc);

-- ----------------------------------------------------------------------------
-- Matches / solicitudes de cotización
-- ----------------------------------------------------------------------------
create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  productor_id uuid not null references public.productores(id) on delete cascade,
  empresa_id uuid not null references public.empresas_turisticas(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete set null,
  cantidad int not null default 1 check (cantidad > 0),
  compatibilidad int not null default 0 check (compatibilidad between 0 and 100),
  descripcion_acuerdo text not null default '',
  monto_estimado_cordobas numeric(14,2) not null default 0 check (monto_estimado_cordobas >= 0),
  estado text not null default 'Pendiente'
    check (estado in ('Pendiente', 'Aprobado', 'Rechazado', 'En_Negociacion', 'Finalizado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists matches_producto_idx on public.matches(producto_id);
create index if not exists matches_empresa_idx on public.matches(empresa_id);
create index if not exists matches_productor_idx on public.matches(productor_id);

-- Evita dos solicitudes pendientes idénticas incluso con concurrencia.
create unique index if not exists matches_pendiente_unica
  on public.matches(producto_id, empresa_id)
  where estado = 'Pendiente' and producto_id is not null;

-- ----------------------------------------------------------------------------
-- Notificaciones
-- ----------------------------------------------------------------------------
create table if not exists public.notificaciones (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.profiles(id) on delete cascade,
  titulo text not null default '',
  mensaje text not null default '',
  tipo text not null default 'info',
  leido boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notificaciones_usuario_idx
  on public.notificaciones(usuario_id, created_at desc);

-- ----------------------------------------------------------------------------
-- Funcionarios INTUR
-- ----------------------------------------------------------------------------
create table if not exists public.intur_admins (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  departamento_id bigint references public.departamentos(id) on delete set null,
  cargo text not null default 'Funcionario INTUR',
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- Actualización automática de updated_at
-- ----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists productores_set_updated_at on public.productores;
create trigger productores_set_updated_at
before update on public.productores
for each row execute function public.set_updated_at();

drop trigger if exists empresas_set_updated_at on public.empresas_turisticas;
create trigger empresas_set_updated_at
before update on public.empresas_turisticas
for each row execute function public.set_updated_at();

drop trigger if exists productos_set_updated_at on public.productos;
create trigger productos_set_updated_at
before update on public.productos
for each row execute function public.set_updated_at();

drop trigger if exists matches_set_updated_at on public.matches;
create trigger matches_set_updated_at
before update on public.matches
for each row execute function public.set_updated_at();

commit;
