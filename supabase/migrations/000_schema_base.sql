begin;

create extension if not exists pgcrypto;

-- ----------------------------------------------------------------------------
-- Perfiles (1:1 con auth.users)
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  nombre_completo text not null default '',
  telefono text default '',
  rol text not null default 'productor'
    check (rol in ('productor', 'empresa', 'intur')),
  avatar_url text,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists profiles_rol_idx on public.profiles(rol);

-- ----------------------------------------------------------------------------
-- Catálogos base
-- ----------------------------------------------------------------------------
create table if not exists public.departamentos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  region text not null default ''
);

create table if not exists public.rubros (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text not null default '',
  icono text not null default 'category'
);

-- Semilla de catálogos. Se puede ampliar desde el SQL Editor.
insert into public.departamentos (nombre, region) values
