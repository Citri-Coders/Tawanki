  ('Rivas',          'Pacífico'),
  ('Matagalpa',      'Centro-Norte'),
  ('Estelí',         'Centro-Norte'),
  ('Carazo',         'Pacífico'),
  ('Managua',        'Pacífico'),
  ('Jinotega',       'Centro-Norte'),
  ('Nueva Segovia',  'Centro-Norte'),
  ('Boaco',          'Centro-Norte'),
